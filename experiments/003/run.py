"""Experiment 003: hybrid wirings + KC code diagnostics. See PLAN.md.

    uv run python experiments/003/run.py [--seeds 30] [--procs 10]
"""
import argparse
import importlib.util
import json
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

from neuralpet import mb

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
spec = importlib.util.spec_from_file_location("run001", ROOT / "experiments" / "001" / "run.py")
run001 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(run001)

HYBRIDS = [("real", "real"), ("real", "shuffle"), ("shuffle", "real"), ("shuffle", "shuffle")]
OUT = ROOT / "reports" / "003"


def name(c):
    return f"PK:{c[0]}/KM:{c[1]}"


def run_hybrid(args):
    seed, cond, sp, frac = args
    r = run001.run_one((seed, cond, sp, frac))
    r["wiring"] = name(cond)
    return r


def gini(x):
    x = np.sort(np.asarray(x, float))
    n = len(x)
    return float((2 * np.arange(1, n + 1) - n - 1) @ x / (n * x.sum())) if x.sum() > 0 else 0.0


def diagnostics(args):
    cond, sample, frac = args
    W_pk, W_km, glom = run001.load()
    W, _ = mb.make_wiring((cond, "real"), W_pk, W_km, np.random.default_rng([sample, 500]))
    odors = mb.make_odors(200, glom, np.random.default_rng(777))
    kc = mb.kc_code(odors, W, frac)
    inter = kc @ kc.T
    sizes = kc.sum(1)
    union = sizes[:, None] + sizes[None, :] - inter
    iu = np.triu_indices(len(kc), 1)
    jac = float(np.mean(inter[iu] / np.maximum(union[iu], 1)))
    ev = np.linalg.svd(kc - kc.mean(0), compute_uv=False) ** 2   # covariance eigenvalues (x n)
    pr = float(ev.sum() ** 2 / (ev ** 2).sum())
    p = kc.mean(0)
    unit_tot = np.bincount(glom, weights=W.sum(1))
    return dict(pk=cond, sample=sample, frac=frac, jaccard=jac, dim_pr=pr,
                frac_kc_ever=float((p > 0).mean()), gini_kc_rate=gini(p), gini_input_unit=gini(unit_tot))


def boot(x, n=10000):
    x = np.asarray(x, float)
    m = np.random.default_rng(0).choice(x, (n, len(x))).mean(1)
    return x.mean(), *np.percentile(m, [2.5, 97.5])


def f(t):
    return f"{t[0]:.3g} [{t[1]:.3g}, {t[2]:.3g}]"


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--seeds", type=int, default=30)
    a.add_argument("--procs", type=int, default=10)
    a = a.parse_args()
    W_pk, _, glom = run001.load()
    fr = {"sparse": 0.10, "literal": run001.literal_fraction(W_pk, glom)}
    (HERE / "results").mkdir(exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    with Pool(a.procs) as pool:
        rows = pool.map(run_hybrid, [(s, c, sp, fr[sp]) for s in range(a.seeds)
                                     for c in HYBRIDS for sp in fr], chunksize=1)
        diag = pool.map(diagnostics, [(c, s, fr[sp]) for sp in fr for c in ["real", "shuffle", "random"]
                                      for s in (range(1) if c == "real" else range(a.seeds))])
    df, dg = pd.DataFrame(rows), pd.DataFrame(diag)
    df.to_csv(HERE / "results" / "hybrid_runs.csv", index=False)
    dg.to_csv(HERE / "results" / "diagnostics.csv", index=False)

    # interference relative to what was learned (secondary), also for 001
    d1 = pd.read_csv(ROOT / "experiments" / "001" / "results" / "runs.csv")
    for d in (df, d1):
        d["M3_relative"] = d.M3_interference / (d.aucA_before - 0.5).clip(lower=0.05)

    L = ["# Experiment 003 tables (generated by experiments/003/run.py)\n",
         "Cells: mean [95% bootstrap CI]. PK = PN→KC, KM = KC→MBON.\n"]
    names = [name(c) for c in HYBRIDS]
    for sp in fr:
        d = df[df.sparsity == sp]
        L += [f"\n## Part A, sparsity = {sp} (f = {fr[sp]:.3f}, n = {d.seed.nunique()} seeds)\n",
              "| metric | " + " | ".join(names) + " |", "|---|" + "---|" * 4]
        for m in ["M1_trials", "M2_auc_sigma1.0", "M3_interference", "M3_relative"]:
            L.append(f"| {m} | " + " | ".join(f(boot(d[d.wiring == n][m])) for n in names) + " |")
        p = d.pivot(index="seed", columns="wiring")
        L += ["", "| paired contrast (M1_trials) | mean diff [95% CI] |", "|---|---|"]
        for x, y in [(1, 3), (0, 2), (2, 3), (0, 1)]:
            diff = p["M1_trials"][names[x]] - p["M1_trials"][names[y]]
            L.append(f"| {names[x]} − {names[y]} | {f(boot(diff))} |")
        e = d1[d1.sparsity == sp]
        L.append("\n001 M3_relative (secondary): " + ", ".join(
            f"{c} {f(boot(e[e.wiring == c].M3_relative))}" for c in ["random", "shuffle", "real"]))
    L.append("\n## Part B, KC code diagnostics (200 noise-free v1 odours; real = 1 wiring, "
             f"shuffle/random = {a.seeds} samples)\n")
    for sp in fr:
        g = dg[dg.frac == fr[sp]]
        L += [f"\n### {sp} (f = {fr[sp]:.3f})\n", "| measure | real | shuffle | random |", "|---|---|---|---|"]
        for m in ["jaccard", "dim_pr", "frac_kc_ever", "gini_kc_rate", "gini_input_unit"]:
            L.append(f"| {m} | " + " | ".join(
                f"{g[g.pk == c][m].iloc[0]:.3g}" if c == "real" else f(boot(g[g.pk == c][m]))
                for c in ["real", "shuffle", "random"]) + " |")
    t = "\n".join(L)
    (OUT / "tables.md").write_text(t + "\n")
    (HERE / "results" / "meta.json").write_text(json.dumps(dict(seeds=a.seeds, fractions=fr)))
    print(t)


if __name__ == "__main__":
    main()
