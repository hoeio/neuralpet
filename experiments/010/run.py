"""Experiment 010: confirmatory replication of the wiring question. See PLAN.md.

    uv run python experiments/010/run.py [--seeds 64] [--procs 10] [--report-only]

Raw results: experiments/010/results/runs.csv (never edited). Report: reports/010/tables.md + figures.
"""
import argparse
import json
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

from neuralpet import mb, nulls, stats, task
from neuralpet.odors import door_odors, hallem_odors

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "reports" / "010"
SAMPLES = {"fw_right": "mb", "fw_left": "mb_left", "hemibrain": "mb_hemibrain"}
SOURCES = ["door", "hallem"]
SPARS = ["sparse", "literal"]
SEED0 = 1000
FAMILY = [("H1", "real", "shuffle", -1), ("H2", "pn_out", "random", +1), ("H3", "pn_out", "pn_out_perm_live", +1)]
SECONDARY = [("N2-pairing: real − n2a_coconv", "real", "n2a_coconv"),
             ("N2-coconv: n2a_coconv − shuffle", "n2a_coconv", "shuffle"),
             ("N2-class: n2b_subtype − shuffle", "n2b_subtype", "shuffle"),
             ("real − n2b_subtype", "real", "n2b_subtype")]
SESOI = 0.02
_CACHE = {}


def sample(name):
    if name not in _CACHE:
        d = np.load(ROOT / "data" / "mb" / f"{SAMPLES[name]}.npz")
        glom, names = d["glom_of_pn"], d["glom_names"]
        door, keys, _ = door_odors(names, glom)
        _CACHE[name] = dict(W_pk=d["W_pnkc"], W_km=d["W_kcmbon"], glom=glom, cls=nulls.kc_class(d["kc_type"]),
                            live=door.sum(0) > 0, pools={"door": door, "hallem": hallem_odors(names, glom, exclude=keys)[0]},
                            literal=float(((mb.make_odors(500, glom, np.random.default_rng(12345)) @ d["W_pnkc"]) > 0).mean()))
    return _CACHE[name]


def job(args):
    seed, smp, cond = args
    S = sample(smp)
    W_pk = nulls.make_pk(cond, S["W_pk"], np.random.default_rng([seed, list(SAMPLES).index(smp), nulls.CONDS.index(cond)]),
                         S["cls"], S["live"])
    rows = []
    for so in SOURCES:
        # odour sets depend on (seed, source) only: the same odorants in every condition and sample
        A, B = task.pick_sets(S["pools"][so], task.P["n"], np.random.default_rng([seed, 31, SOURCES.index(so)]))
        for sp in SPARS:
            frac = 0.10 if sp == "sparse" else S["literal"]
            r = task.run(W_pk, S["W_km"], A, B, seed, frac)
            r["curve"] = json.dumps(r["curve"])
            rows.append(dict(seed=seed, sample=smp, cond=cond, source=so, sparsity=sp, frac=frac, **r))
    return rows


def paired(df, sp, a, b, metric="m2", by=None):
    """Per-seed difference a − b averaged over samples and sources (or within one `by` cell)."""
    d = df[df.sparsity == sp]
    if by:
        d = d[(d[by[0]] == by[1])]
    p = d.pivot_table(index=["seed", "sample", "source"], columns="cond", values=metric)
    return (p[a] - p[b]).groupby(level="seed").mean()


def tables(df):
    L = ["# Experiment 010 tables (generated by experiments/010/run.py)\n",
         f"{df.seed.nunique()} seeds ({df.seed.min()}–{df.seed.max()}), samples {list(SAMPLES)}, odour sources {SOURCES}. "
         "Per-seed values are averaged over samples × sources unless a row says otherwise. "
         "CIs: 95% bootstrap (10,000 resamples of seeds); p: paired t-test, Holm-adjusted across the 6-test family.\n"]
    fam = []
    for h, a, b, sign in FAMILY:
        for sp in SPARS:
            x = paired(df, sp, a, b)
            fam.append(dict(h=h, a=a, b=b, sign=sign, sp=sp, x=x, p=stats.ttest_p(x)))
    adj = stats.holm([f["p"] for f in fam])
    L += ["## Confirmatory family (primary metric M2)\n",
          "| hyp | contrast | sparsity | mean diff [95% CI] | 90% CI | d_z | p | p Holm | verdict |", "|---|---|---|---|---|---|---|---|---|"]
    for f, pa in zip(fam, adj):
        m, lo, hi = stats.boot_ci(f["x"])
        _, lo90, hi90 = stats.boot_ci(f["x"], level=90)
        v = stats.verdict(m, pa, lo90, hi90, f["sign"], SESOI)
        f.update(pa=pa, verdict=v)
        L.append(f"| {f['h']} | {f['a']} − {f['b']} | {f['sp']} | {m:.4f} [{lo:.4f}, {hi:.4f}] | [{lo90:.4f}, {hi90:.4f}] | "
                 f"{stats.dz(f['x']):.2f} | {f['p']:.2g} | {pa:.2g} | {v} |")
    L += ["\n## Per connectome sample and per odour source (M2; descriptive, not in the family)\n",
          "| hyp | sparsity | " + " | ".join(SAMPLES) + " | " + " | ".join(SOURCES) + " |", "|---|---|" + "---|" * (len(SAMPLES) + len(SOURCES))]
    for f in fam:
        cells = [stats.fmt(stats.boot_ci(paired(df, f["sp"], f["a"], f["b"], by=("sample", s)))) for s in SAMPLES]
        cells += [stats.fmt(stats.boot_ci(paired(df, f["sp"], f["a"], f["b"], by=("source", s)))) for s in SOURCES]
        L.append(f"| {f['h']} | {f['sp']} | " + " | ".join(cells) + " |")
    L += ["\n## Secondary metrics for the family contrasts (not in the family)\n",
          "| hyp | sparsity | AULC | plateau | M3 (interference, lower better) |", "|---|---|---|---|---|"]
    for f in fam:
        L.append(f"| {f['h']} | {f['sp']} | " + " | ".join(stats.fmt(stats.boot_ci(paired(df, f["sp"], f["a"], f["b"], m)))
                                                       for m in ["aulc", "plateau", "m3"]) + " |")
    L += ["\n## Pre-specified secondary contrasts: N2 nulls (not in the family)\n",
          "| contrast | sparsity | M2 | AULC | " + " | ".join(f"M2 {s}" for s in SAMPLES) + " |", "|---|---|---|---|" + "---|" * len(SAMPLES)]
    for lab, a, b in SECONDARY:
        for sp in SPARS:
            cells = [stats.fmt(stats.boot_ci(paired(df, sp, a, b, m))) for m in ["m2", "aulc"]]
            cells += [stats.fmt(stats.boot_ci(paired(df, sp, a, b, by=("sample", s)))) for s in SAMPLES]
            L.append(f"| {lab} | {sp} | " + " | ".join(cells) + " |")
    L += ["\n## Condition means (M2, AULC, plateau; averaged over samples × sources)\n",
          "| cond | sparsity | M2 | AULC | plateau | M3 | KC active |", "|---|---|---|---|---|---|---|"]
    for sp in SPARS:
        for c in nulls.CONDS:
            d = df[(df.sparsity == sp) & (df.cond == c)].groupby("seed")
            L.append(f"| {c} | {sp} | " + " | ".join(stats.fmt(stats.boot_ci(d[m].mean())) for m in ["m2", "aulc", "plateau", "m3", "kc_active"]) + " |")
    floor = df.groupby(["sample", "source", "sparsity", "cond"]).plateau.agg(["mean", "min", "max"])
    L.append(f"\nFloor/ceiling check: cell-mean plateau ranges {floor['mean'].min():.3f}–{floor['mean'].max():.3f}; "
             f"runs with plateau ≥ 0.99: {int((df.plateau >= 0.99).sum())} of {len(df)}; runs with AULC ≤ 0.55: {int((df.aulc <= 0.55).sum())}.")
    return "\n".join(L), fam


def figure(df):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from neuralpet.plotstyle import COLORS, style
    style()
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4), sharey=True)
    for ax, sp in zip(axes, SPARS):
        for k, (h, a, b, _) in enumerate(FAMILY):
            for j, s in enumerate(list(SAMPLES) + ["pooled"]):
                x = paired(df, sp, a, b) if s == "pooled" else paired(df, sp, a, b, by=("sample", s))
                m, lo, hi = stats.boot_ci(x)
                y = k + (j - 1.5) * 0.18
                ax.plot([lo, hi], [y, y], color=COLORS[j], lw=2 if s == "pooled" else 1.2)
                ax.plot(m, y, "o", color=COLORS[j], ms=6 if s == "pooled" else 4, label=s if k == 0 else None)
        ax.axvline(0, color="#52514e", lw=1)
        for v in (-SESOI, SESOI):
            ax.axvline(v, color="#52514e", lw=0.8, ls=":")
        ax.set_yticks(range(3), [f"{h}: {a} − {b}" for h, a, b, _ in FAMILY])
        ax.set(title=f"{sp} KC code", xlabel="Δ M2 (AUC at test noise σ=1)")
    axes[0].legend(frameon=False, fontsize=7, loc="lower left")
    axes[0].invert_yaxis()
    fig.tight_layout()
    fig.savefig(OUT / "effects.png", dpi=150)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=64)
    ap.add_argument("--procs", type=int, default=10)
    ap.add_argument("--report-only", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    res = HERE / "results"
    if not a.report_only:
        jobs = [(SEED0 + s, smp, c) for s in range(a.seeds) for smp in SAMPLES for c in nulls.CONDS]
        t = time.time()
        with Pool(a.procs) as pool:
            rows = [r for rs in pool.imap_unordered(job, jobs, chunksize=2) for r in rs]
        res.mkdir(exist_ok=True)
        df = pd.DataFrame(rows).sort_values(["seed", "sample", "cond", "source", "sparsity"])
        df.to_csv(res / "runs.csv", index=False)
        (res / "meta.json").write_text(json.dumps(dict(seeds=[SEED0, SEED0 + a.seeds - 1], task=task.P,
                                                       literal={s: sample(s)["literal"] for s in SAMPLES},
                                                       wall_s=round(time.time() - t, 1)), indent=1))
    df = pd.read_csv(res / "runs.csv")
    t, _ = tables(df)
    (OUT / "tables.md").write_text(t + "\n")
    figure(df)
    print(t)


if __name__ == "__main__":
    main()
