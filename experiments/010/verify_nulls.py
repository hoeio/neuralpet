"""WP2: verify by computed statistics what each PN->KC null keeps and destroys, per connectome sample.

    uv run python experiments/010/verify_nulls.py      # -> experiments/010/null_stats/null_stats.csv, reports/010/nulls.md
Uses wiring seeds 900-909 (never used by any learning run).
"""
from pathlib import Path

import numpy as np
import pandas as pd

from neuralpet import mb, nulls
from neuralpet.odors import door_odors

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SAMPLES = {"fw_right": "mb", "fw_left": "mb_left", "hemibrain": "mb_hemibrain"}


def main():
    rows = []
    for s, f in SAMPLES.items():
        d = np.load(ROOT / "data" / "mb" / f"{f}.npz")
        W, glom, cls = d["W_pnkc"], d["glom_of_pn"], nulls.kc_class(d["kc_type"])
        live = door_odors(d["glom_names"], glom)[0].sum(0) > 0
        r = np.random.default_rng(12)
        C_exp = np.mean([nulls.coconv(mb.degree_shuffle(W, r), glom) for _ in range(20)], 0)
        for cond in nulls.CONDS:
            for k in range(10):
                Wn = nulls.make_pk(cond, W, np.random.default_rng([900 + k, nulls.CONDS.index(cond)]), cls, live)
                rows.append(dict(sample=s, cond=cond, draw=k, **nulls.stats(Wn, W, glom, cls, C_exp)))
        print("done", s, flush=True)
    df = pd.DataFrame(rows)
    (HERE / "null_stats").mkdir(exist_ok=True)
    df.to_csv(HERE / "null_stats" / "null_stats.csv", index=False)
    g = df.drop(columns="draw").groupby(["sample", "cond"], sort=False).mean().round(3).reset_index()
    out = ROOT / "reports" / "010"
    out.mkdir(parents=True, exist_ok=True)
    cols = list(g.columns)
    L = ["# Null verification (generated by experiments/010/verify_nulls.py)\n",
         "Mean over 10 draws per null. 1 / True = kept exactly. excess_coconv_r = correlation with real of the "
         "glomerulus-pair co-convergence beyond the degree-shuffle expectation (1 = kept, ~0 = destroyed). "
         "kc_input_identical = fraction of input-receiving KCs whose PN input set is unchanged.\n",
         "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    L += ["| " + " | ".join(str(v) for v in row) + " |" for row in g.itertuples(index=False)]
    (out / "nulls.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
