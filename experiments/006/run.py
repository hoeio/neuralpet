"""Experiment 006: DoOR real odours vs random odours. See PLAN.md.

    uv run python experiments/006/run.py [--seeds 30] [--procs 10] [--report-only]
"""
import argparse
import importlib.util
import json
import time
from multiprocessing import Pool
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from neuralpet import mb
from neuralpet.odors import door_odors

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "reports" / "006"
N = 18                       # odours per set (9 CS+, 9 CS-)
SOURCES = ["random", "door"]


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


r1 = _load("run001", ROOT / "experiments" / "001" / "run.py")
rep = _load("report001", ROOT / "experiments" / "001" / "report.py")


def run_one(args):
    seed, source, cond, sparsity, frac = args
    W_pk0, W_km0, glom = r1.load()
    W_pk, W_km = mb.make_wiring(cond, W_pk0, W_km0, np.random.default_rng([seed, r1.cond_id(cond)]))
    W = W_km.astype(np.float64).copy()
    W0 = W.copy()
    task = np.random.default_rng([seed, 99])
    noise = np.random.default_rng([seed, 7])
    if source == "door":
        names = np.load(ROOT / "data" / "mb" / "mb.npz")["glom_names"]
        O, _, _ = door_odors(names, glom)
        perm = task.permutation(len(O))
        A, B = O[perm[:N]], O[perm[N:2 * N]]
    else:
        A, B = mb.make_odors(N, glom, task), mb.make_odors(N, glom, task)
    vA = task.permutation(np.r_[np.ones(N // 2), np.zeros(N // 2)])
    vB = task.permutation(np.r_[np.ones(N // 2), np.zeros(N // 2)])

    def evaluate(odors, val, Wt, sigma, reps=10):
        X, y = np.repeat(odors, reps, 0), np.repeat(val, reps)
        kc = mb.kc_code(mb.pn_rates(X, sigma, noise), W_pk, frac)
        R = mb.mbon_out(kc, Wt)
        ratio = R / np.maximum(mb.mbon_out(kc, W0), 1e-9)
        return mb.auc(R[y == 1], R[y == 0]), mb.auc(ratio[y == 1], ratio[y == 0])

    def train_block(odors, val, Wt):
        for i in noise.permutation(len(odors)):
            kc = mb.kc_code(mb.pn_rates(odors[i:i + 1], r1.SIG, noise), W_pk, frac)[0]
            mb.learn(Wt, kc, float(val[i]), r1.ETA)

    curve = [evaluate(A, vA, W, r1.SIG)]
    for b in range(r1.BLOCKS):
        train_block(A, vA, W)
        curve.append(evaluate(A, vA, W, r1.SIG))
        if b + 1 == r1.SNAP:
            W_snap = W.copy()
    row = dict(seed=seed, source=source, wiring=cond, sparsity=sparsity, frac=frac)
    for k, sfx in enumerate(["_pooled", "_ratio"]):
        c = [a[k] for a in curve]
        hit = [i for i, a in enumerate(c) if a >= r1.CRIT]
        row[f"M1{sfx}"] = hit[0] * N if hit else r1.BLOCKS * N + 10
        row[f"M1_censored{sfx}"] = not hit
        row[f"curve{sfx}"] = json.dumps(c)
    for s in r1.TEST_SIGMAS:
        row[f"auc_pooled_sigma{s}"], row[f"auc_ratio_sigma{s}"] = evaluate(A, vA, W_snap, s)
    row["M2_pooled"], row["M2_ratio"] = row["auc_pooled_sigma1.0"], row["auc_ratio_sigma1.0"]
    Wb = W_snap.copy()
    before = evaluate(A, vA, Wb, r1.SIG)
    for _ in range(r1.BLOCKS_B):
        train_block(B, vB, Wb)
    after = evaluate(A, vA, Wb, r1.SIG)
    row["M3_pooled"], row["M3_ratio"] = before[0] - after[0], before[1] - after[1]
    return row


def f(t):
    return f"{t[0]:.3g} [{t[1]:.3g}, {t[2]:.3g}]"


def tables(df):
    L = ["# Experiment 006 tables (generated by experiments/006/run.py)\n",
         "Cells: mean [95% bootstrap CI], paired by seed. Primary readout = ratio; pooled = secondary.\n"]
    mets = ["M1_ratio", "M2_ratio", "M3_ratio", "M1_pooled", "M2_pooled", "M3_pooled"]
    for sp in df.sparsity.unique():
        d = df[df.sparsity == sp]
        L += [f"\n## sparsity = {sp} (f = {d.frac.iloc[0]:.3f}, n = {d.seed.nunique()} seeds)\n",
              "| metric | odours | random wiring | shuffle | real |", "|---|---|---|---|---|"]
        for m in mets:
            for so in SOURCES:
                L.append(f"| {m} | {so} | " + " | ".join(
                    f(rep.boot_ci(d[(d.source == so) & (d.wiring == c)][m])) for c in rep.CONDS) + " |")
        cens = {(so, c): int(d[(d.source == so) & (d.wiring == c)].M1_censored_ratio.sum())
                for so in SOURCES for c in rep.CONDS}
        L.append(f"\nM1 (ratio) censored, not learned by {r1.BLOCKS * N} trials: {cens}\n")
        L += ["| contrast | metric | mean diff [95% CI] | d_z |", "|---|---|---|---|"]
        k = d.set_index(["seed", "source", "wiring"])

        def get(m, so, c):
            return k.xs((so, c), level=["source", "wiring"])[m]

        for m in mets:
            rows = [(f"Q1 real − shuffle ({so} odours)", get(m, so, "real") - get(m, so, "shuffle"))
                    for so in ["door", "random"]]
            rows.append(("real − random wiring (door odours)", get(m, "door", "real") - get(m, "door", "random")))
            rows.append(("Q2 interaction: (real − shuffle | door) − (real − shuffle | random)",
                         (get(m, "door", "real") - get(m, "door", "shuffle"))
                         - (get(m, "random", "real") - get(m, "random", "shuffle"))))
            for lab, diff in rows:
                sd = diff.std(ddof=1)
                L.append(f"| {lab} | {m} | {f(rep.boot_ci(diff))} | "
                         f"{diff.mean() / sd if sd > 0 else float('nan'):.2f} |")
    return "\n".join(L)


def figure(df):
    sps = list(df.sparsity.unique())
    fig, axes = plt.subplots(len(sps), 2, figsize=(9, 3.2 * len(sps)), sharey=True, squeeze=False)
    for i, sp in enumerate(sps):
        for j, so in enumerate(SOURCES):
            ax, ends = axes[i, j], []
            for c in rep.CONDS:
                cur = np.array([json.loads(s) for s in
                                df[(df.sparsity == sp) & (df.source == so) & (df.wiring == c)].curve_ratio])
                x = np.arange(cur.shape[1]) * N
                lo, hi = np.array([rep.boot_ci(cur[:, q])[1:] for q in range(cur.shape[1])]).T
                ax.fill_between(x, lo, hi, color=rep.COLOR[c], alpha=0.18, lw=0)
                ax.plot(x, cur.mean(0), color=rep.COLOR[c], lw=2, label=c)
                ends.append((x[-1], cur.mean(0)[-1], c))
            rep.label_ends(ax, ends)
            ax.axhline(0.9, color=rep.INK2, lw=1, ls=":")
            ax.set(title=f"{sp} code, {'DoOR' if so == 'door' else 'random'} odours",
                   xlim=(0, 420), xlabel="training trials")
        axes[i, 0].set_ylabel("AUC (ratio readout)")
    axes[0, 0].legend(frameon=False, loc="lower right")
    fig.tight_layout()
    fig.savefig(OUT / "learning_curves.png", dpi=150)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--seeds", type=int, default=30)
    a.add_argument("--procs", type=int, default=10)
    a.add_argument("--report-only", action="store_true")
    a = a.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    res = HERE / "results"
    if not a.report_only:
        W_pk, _, glom = r1.load()
        fr = {"sparse": 0.10, "literal": r1.literal_fraction(W_pk, glom)}
        jobs = [(s, so, c, sp, fr[sp]) for s in range(a.seeds) for so in SOURCES for c in r1.CONDS
                for sp in r1.SPARSITIES]
        t = time.time()
        with Pool(a.procs) as pool:
            rows = pool.map(run_one, jobs, chunksize=1)
        res.mkdir(exist_ok=True)
        pd.DataFrame(rows).to_csv(res / "runs.csv", index=False)
        (res / "meta.json").write_text(json.dumps(dict(seeds=a.seeds, fractions=fr, n_per_set=N,
                                                       wall_s=round(time.time() - t, 1))))
    df = pd.read_csv(res / "runs.csv")
    t = tables(df)
    (OUT / "tables.md").write_text(t + "\n")
    figure(df)
    print(t)


if __name__ == "__main__":
    main()
