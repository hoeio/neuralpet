"""Experiment 005: compartment readout (adapters v3). See PLAN.md.

    uv run python experiments/005/run.py [--seeds 30] [--procs 10]
"""
import argparse
import importlib.util
import json
import time
from multiprocessing import Pool
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from neuralpet import mb

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "reports" / "005"


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


r1 = _load("run001", ROOT / "experiments" / "001" / "run.py")
rep = _load("report001", ROOT / "experiments" / "001" / "report.py")
GROUPINGS = ["real", "random"]
GATE_SYN, N_REF = 20, 100


def plastic_set():
    d = np.load(ROOT / "data" / "mb" / "mb.npz")
    ppl1 = np.char.startswith(d["dan_type"], "PPL1")
    return np.flatnonzero((d["W_danmbon"][ppl1] >= GATE_SYN).any(0))


def run_one(args):
    seed, cond, grouping, sparsity, frac = args
    W_pk0, W_km0, glom = r1.load()
    n_mbon = W_km0.shape[1]
    W_pk, W_km = mb.make_wiring(cond, W_pk0, W_km0, np.random.default_rng([seed, r1.cond_id(cond)]))
    W = W_km.astype(np.float64).copy()
    W0 = W.copy()
    P_real = plastic_set()
    P = P_real if grouping == "real" else np.random.default_rng([seed, 55]).choice(n_mbon, len(P_real), False)
    mask = np.zeros(n_mbon)
    mask[P] = 1
    ref = mb.make_odors(N_REF, glom, np.random.default_rng(4242))
    mu = (mb.kc_code(ref, W_pk, frac) @ W).mean(0)
    gain = np.where((mask > 0) & (mu > 0), 1 / np.maximum(mu, 1e-12), 0.0)

    task = np.random.default_rng([seed, 99])
    noise = np.random.default_rng([seed, 7])
    A, vA = r1.task_set(task, glom)
    B, vB = r1.task_set(task, glom)

    def evaluate(odors, val, Wt, sigma, reps=10):
        X, y = np.repeat(odors, reps, 0), np.repeat(val, reps)
        kc = mb.kc_code(mb.pn_rates(X, sigma, noise), W_pk, frac)
        Rm = kc @ Wt
        s = Rm @ gain
        ratio = (Rm @ mask) / np.maximum((kc @ W0) @ mask, 1e-9)
        return mb.auc(s[y == 1], s[y == 0]), mb.auc(ratio[y == 1], ratio[y == 0])

    def train_block(odors, val, Wt):
        for i in noise.permutation(len(odors)):
            kc = mb.kc_code(mb.pn_rates(odors[i:i + 1], r1.SIG, noise), W_pk, frac)[0]
            Wt[:, P] *= (1 - r1.ETA * float(val[i]) * kc)[:, None]

    curve = [evaluate(A, vA, W, r1.SIG)]
    for b in range(r1.BLOCKS):
        train_block(A, vA, W)
        curve.append(evaluate(A, vA, W, r1.SIG))
        if b + 1 == r1.SNAP:
            W_snap = W.copy()
    row = dict(seed=seed, wiring=cond, grouping=grouping, sparsity=sparsity, frac=frac,
               n_plastic_with_input=int(((mu > 0) & (mask > 0)).sum()))
    for k, name in enumerate(["", "_ratio"]):
        c = [a[k] for a in curve]
        hit = [i for i, a in enumerate(c) if a >= r1.CRIT]
        row[f"M1_trials{name}"] = hit[0] * r1.N_ODORS if hit else r1.BLOCKS * r1.N_ODORS + 10
        row[f"M1_censored{name}"] = not hit
        row[f"curve{name}"] = json.dumps(c)
    for s in r1.TEST_SIGMAS:
        a, b2 = evaluate(A, vA, W_snap, s)
        row[f"auc_sigma{s}"], row[f"auc_ratio_sigma{s}"] = a, b2
    row["M2_auc_sigma1.0"], row["M2_auc_sigma1.0_ratio"] = row["auc_sigma1.0"], row["auc_ratio_sigma1.0"]
    Wb = W_snap.copy()
    before = evaluate(A, vA, Wb, r1.SIG)
    for _ in range(r1.BLOCKS_B):
        train_block(B, vB, Wb)
    after = evaluate(A, vA, Wb, r1.SIG)
    row["M3_interference"], row["M3_interference_ratio"] = before[0] - after[0], before[1] - after[1]
    row["aucA_before"], row["aucB"] = before[0], evaluate(B, vB, Wb, r1.SIG)[0]
    return row


def f(t):
    return f"{t[0]:.3g} [{t[1]:.3g}, {t[2]:.3g}]"


def tables(df):
    L = ["# Experiment 005 tables (generated by experiments/005/run.py)\n",
         "Cells: mean [95% bootstrap CI], 30 seeds, paired by seed. Primary readout = normalised "
         "compartment sum; `_ratio` = secondary ratio readout.\n"]
    mets = ["M1_trials", "M2_auc_sigma1.0", "M3_interference"]
    for sp in df.sparsity.unique():
        d = df[df.sparsity == sp]
        L += [f"\n## sparsity = {sp} (f = {d.frac.iloc[0]:.3f})\n",
              "| metric | grouping | random wiring | shuffle | real |", "|---|---|---|---|---|"]
        for m in mets + [x + "_ratio" for x in mets]:
            for g in GROUPINGS:
                L.append(f"| {m} | {g} | " + " | ".join(
                    f(rep.boot_ci(d[(d.wiring == c) & (d.grouping == g)][m])) for c in rep.CONDS) + " |")
        cens = {(c, g): int(d[(d.wiring == c) & (d.grouping == g)].M1_censored.sum())
                for g in GROUPINGS for c in rep.CONDS}
        L.append(f"\nM1 censored (primary, not learned by 400 trials): {cens}\n")
        L += ["| contrast | metric | mean diff [95% CI] | d_z |", "|---|---|---|---|"]
        key = d.set_index(["seed", "wiring", "grouping"])
        for m in mets + [x + "_ratio" for x in mets]:
            pairs = [("Q1 real − shuffle wiring (real grouping)", ("real", "real"), ("shuffle", "real")),
                     ("Q1 real − random wiring (real grouping)", ("real", "real"), ("random", "real")),
                     ("Q2 real − random grouping (real wiring)", ("real", "real"), ("real", "random")),
                     ("exploratory: real − random grouping (shuffle wiring)", ("shuffle", "real"),
                      ("shuffle", "random"))]
            for lab, x, y in pairs:
                diff = (key.xs(x, level=["wiring", "grouping"])[m]
                        - key.xs(y, level=["wiring", "grouping"])[m])
                sd = diff.std(ddof=1)
                L.append(f"| {lab} | {m} | {f(rep.boot_ci(diff))} | "
                         f"{diff.mean() / sd if sd > 0 else float('nan'):.2f} |")
    L.append(f"\nPlastic MBONs with KC input (real grouping, real wiring): "
             f"{int(df[(df.wiring == 'real') & (df.grouping == 'real')].n_plastic_with_input.iloc[0])} of 15")
    return "\n".join(L)


def figure(df):
    sps = list(df.sparsity.unique())
    fig, axes = plt.subplots(len(sps), 2, figsize=(9, 3.2 * len(sps)), sharey=True, squeeze=False)
    for i, sp in enumerate(sps):
        for j, g in enumerate(GROUPINGS):
            ax, ends = axes[i, j], []
            for c in rep.CONDS:
                cur = np.array([json.loads(s) for s in
                                df[(df.sparsity == sp) & (df.wiring == c) & (df.grouping == g)].curve])
                x = np.arange(cur.shape[1]) * r1.N_ODORS
                lo, hi = np.array([rep.boot_ci(cur[:, k])[1:] for k in range(cur.shape[1])]).T
                ax.fill_between(x, lo, hi, color=rep.COLOR[c], alpha=0.18, lw=0)
                ax.plot(x, cur.mean(0), color=rep.COLOR[c], lw=2, label=c)
                ends.append((x[-1], cur.mean(0)[-1], c))
            rep.label_ends(ax, ends)
            ax.axhline(0.9, color=rep.INK2, lw=1, ls=":")
            ax.set(title=f"{sp} code, {g} compartment grouping", xlim=(0, 470), xlabel="training trials")
        axes[i, 0].set_ylabel("AUC (compartment readout)")
    axes[0, 0].legend(frameon=False, loc="lower right")
    fig.tight_layout()
    fig.savefig(OUT / "learning_curves.png", dpi=150)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--seeds", type=int, default=30)
    a.add_argument("--procs", type=int, default=10)
    a.add_argument("--report-only", action="store_true", help="rebuild tables/figure from results/runs.csv")
    a = a.parse_args()
    if a.report_only:
        df = pd.read_csv(HERE / "results" / "runs.csv")
        (OUT / "tables.md").write_text(tables(df) + "\n")
        return figure(df)
    W_pk, _, glom = r1.load()
    fr = {"sparse": 0.10, "literal": r1.literal_fraction(W_pk, glom)}
    jobs = [(s, c, g, sp, fr[sp]) for s in range(a.seeds) for c in r1.CONDS for g in GROUPINGS
            for sp in r1.SPARSITIES]
    t = time.time()
    with Pool(a.procs) as pool:
        rows = pool.map(run_one, jobs, chunksize=1)
    res = HERE / "results"
    res.mkdir(exist_ok=True)
    OUT.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(rows)
    df.to_csv(res / "runs.csv", index=False)
    (res / "meta.json").write_text(json.dumps(dict(
        seeds=a.seeds, fractions=fr, gate_syn=GATE_SYN, n_ref=N_REF,
        plastic_set_size=int(len(plastic_set())), wall_s=round(time.time() - t, 1))))
    t = tables(df)
    (OUT / "tables.md").write_text(t + "\n")
    figure(df)
    print(t)


if __name__ == "__main__":
    main()
