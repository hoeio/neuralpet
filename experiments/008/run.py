"""Experiment 008: is the real PN <-> out-degree pairing what helps?. See PLAN.md.

    uv run python experiments/008/run.py [--seeds 30] [--procs 10] [--report-only]
"""
import argparse
import importlib.util
import json
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "reports" / "008"
PK = ["random", "pn_out_perm", "pn_out", "shuffle_perm", "shuffle", "real_perm", "real"]


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


r6 = _load("run006", ROOT / "experiments" / "006" / "run.py")
rep = r6.rep


def job(args):
    seed, source, pk, sp, frac = args
    row = r6.run_one((seed, source, (pk, "real"), sp, frac))
    row["wiring"] = pk
    row["plateau_ratio"] = json.loads(row["curve_ratio"])[-1]
    return row


def f(t):
    return f"{t[0]:.3g} [{t[1]:.3g}, {t[2]:.3g}]"


def tables(df):
    L = ["# Experiment 008 tables (generated by experiments/008/run.py)\n",
         "PN→KC variants; KC→MBON real everywhere. Cells: mean [95% bootstrap CI], 30 seeds, paired.\n"]
    mets = ["M2_ratio", "plateau_ratio", "M3_ratio", "M2_pooled"]
    for sp in df.sparsity.unique():
        for so in ["door", "random"]:
            d = df[(df.sparsity == sp) & (df.source == so)]
            L += [f"\n## {so} odours, sparsity = {sp}\n", "| metric | " + " | ".join(PK) + " |",
                  "|---|" + "---|" * len(PK)]
            for m in mets:
                L.append(f"| {m} | " + " | ".join(f(rep.boot_ci(d[d.wiring == c][m])) for c in PK) + " |")
            p = d.pivot(index="seed", columns="wiring")
            L += ["", "| contrast | metric | mean diff [95% CI] | d_z |", "|---|---|---|---|"]
            for lab, a, b in [("Q1 pn_out − pn_out_perm", "pn_out", "pn_out_perm"),
                              ("Q2 pn_out_perm − random", "pn_out_perm", "random"),
                              ("Q3 shuffle − shuffle_perm", "shuffle", "shuffle_perm"),
                              ("Q4 real_perm − real", "real_perm", "real"),
                              ("ref pn_out − random", "pn_out", "random"), ("ref real − shuffle", "real", "shuffle")]:
                for m in mets[:3]:
                    diff = p[m][a] - p[m][b]
                    sd = diff.std(ddof=1)
                    L.append(f"| {lab} | {m} | {f(rep.boot_ci(diff))} | {diff.mean() / sd if sd > 0 else float('nan'):.2f} |")
    return "\n".join(L)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--seeds", type=int, default=30)
    a.add_argument("--procs", type=int, default=10)
    a.add_argument("--report-only", action="store_true")
    a = a.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    res = HERE / "results"
    if not a.report_only:
        W_pk, _, glom = r6.r1.load()
        fr = {"sparse": 0.10, "literal": r6.r1.literal_fraction(W_pk, glom)}
        jobs = [(s, so, pk, sp, fr[sp]) for s in range(a.seeds) for so in ["door", "random"] for pk in PK
                for sp in fr]
        t = time.time()
        with Pool(a.procs) as pool:
            rows = pool.map(job, jobs, chunksize=1)
        res.mkdir(exist_ok=True)
        pd.DataFrame(rows).to_csv(res / "runs.csv", index=False)
        (res / "meta.json").write_text(json.dumps(dict(seeds=a.seeds, fractions=fr, wall_s=round(time.time() - t, 1))))
    t = tables(pd.read_csv(res / "runs.csv"))
    (OUT / "tables.md").write_text(t + "\n")
    print(t)


if __name__ == "__main__":
    main()
