"""Experiment 011: do 010's wiring conclusions survive graded APL feedback and compartment DA? See PLAN.md.

    uv run python experiments/011/run.py [--seeds 64] [--procs 10] [--report-only]
"""
import argparse
import importlib.util
import json
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

from neuralpet import apl, nulls, stats, task

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "reports" / "011"
spec = importlib.util.spec_from_file_location("run010", ROOT / "experiments" / "010" / "run.py")
r10 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r10)
SAMPLES, SOURCES, FAMILY = r10.SAMPLES, r10.SOURCES, r10.FAMILY
CONDS = ["random", "shuffle", "pn_out", "pn_out_perm_live", "real"]
VARIANTS = ["apl_comp", "apl_global", "kwta_comp"]
SEED0 = 1100
RES010 = "results_registered"   # which 010 run to compare with (same parameters as this run)
_C = {}


def extra(smp):
    if smp not in _C:
        d = np.load(ROOT / "data" / "mb" / f"{SAMPLES[smp]}.npz")
        g, D, f = apl.make(d["W_pnkc"], d["W_aplkc"][0], d["W_kcapl"][:, 0], d["glom_of_pn"])
        ppl1 = np.char.startswith(d["dan_type"].astype(str), "PPL1")
        _C[smp] = dict(g=g, D=D, f=f, P=((d["W_danmbon"][ppl1] >= 20).any(0)).astype(float))
    return _C[smp]


def job(args):
    seed, smp, cond = args
    S, E = r10.sample(smp), extra(smp)
    W_pk = nulls.make_pk(cond, S["W_pk"], np.random.default_rng([seed, list(SAMPLES).index(smp), nulls.CONDS.index(cond)]),
                         S["cls"], S["live"])
    rows = []
    for so in SOURCES:
        A, B = task.pick_sets(S["pools"][so], task.P["n"], np.random.default_rng([seed, 31, SOURCES.index(so)]))
        for v in VARIANTS:
            kc_fn = E["f"](W_pk) if v.startswith("apl") else None
            r = task.run(W_pk, S["W_km"], A, B, seed, 0.10, kc_fn=kc_fn, da_mask=E["P"] if v.endswith("comp") else None)
            r["curve"] = json.dumps(r["curve"])
            rows.append(dict(seed=seed, sample=smp, cond=cond, source=so, variant=v, **r))
    return rows


def diff(df, v, a, b, m="m2", smp=None):
    d = df[df.variant == v]
    if smp:
        d = d[d["sample"] == smp]
    p = d.pivot_table(index=["seed", "sample", "source"], columns="cond", values=m)
    return (p[a] - p[b]).groupby(level="seed").mean()


def tables(df):
    d10 = pd.read_csv(ROOT / "experiments" / "010" / RES010 / "runs.csv")
    L = ["# Experiment 011 tables (generated by experiments/011/run.py)\n",
         f"{df.seed.nunique()} seeds ({df.seed.min()}–{df.seed.max()}); sparse; means over samples × sources; 95% bootstrap CIs. "
         "Rules in PLAN.md.\n", "## H1–H3 per model variant (M2) vs experiment 010 (kWTA, global DA)\n",
         "| hyp | 010 (kwta, global) | " + " | ".join(VARIANTS) + " | apl_comp: sign holds | size holds | overturns 010 |",
         "|---|---|" + "---|" * len(VARIANTS) + "---|---|---|"]
    over = []
    for h, a, b, _ in FAMILY:
        ref = stats.boot_ci(r10.paired(d10, "sparse", a, b))
        cells = [stats.boot_ci(diff(df, v, a, b)) for v in VARIANTS]
        m, lo, hi = cells[0]
        _, lo90, hi90 = stats.boot_ci(diff(df, "apl_comp", a, b), level=90)
        sign = (-0.02 < lo90 and hi90 < 0.02) if h == "H1" else (m > 0 and lo > 0)
        size = ref[1] - 0.01 <= m <= ref[2] + 0.01
        ov = lo > 0.02 or hi < -0.02 or (h != "H1" and hi < 0)
        over.append(ov)
        L.append(f"| {h}: {a} − {b} | {stats.fmt(ref)} | " + " | ".join(stats.fmt(c) for c in cells)
                 + f" | {'yes' if sign else 'no'} | {'yes' if size else 'no'} | {'YES' if ov else 'no'} |")
    L.append(f"\n**010 conclusion overturned by apl_comp: {'yes' if any(over) else 'no'}.**\n")
    L += ["## Per sample, apl_comp (M2)\n", "| hyp | " + " | ".join(SAMPLES) + " |", "|---|" + "---|" * len(SAMPLES)]
    for h, a, b, _ in FAMILY:
        L.append(f"| {h} | " + " | ".join(stats.fmt(stats.boot_ci(diff(df, "apl_comp", a, b, smp=s))) for s in SAMPLES) + " |")
    L += ["\n## Secondary: AULC per variant\n", "| hyp | " + " | ".join(VARIANTS) + " |", "|---|" + "---|" * len(VARIANTS)]
    for h, a, b, _ in FAMILY:
        L.append(f"| {h} | " + " | ".join(stats.fmt(stats.boot_ci(diff(df, v, a, b, "aulc"))) for v in VARIANTS) + " |")
    L += ["\n## Condition means\n", "| variant | cond | M2 | AULC | plateau | KC mean rate |", "|---|---|---|---|---|---|"]
    for v in VARIANTS:
        for c in CONDS:
            g = df[(df.variant == v) & (df.cond == c)].groupby("seed")
            L.append(f"| {v} | {c} | " + " | ".join(stats.fmt(stats.boot_ci(g[m].mean())) for m in ["m2", "aulc", "plateau", "kc_active"]) + " |")
    L.append(f"\nRuns with AULC ≤ 0.55: {int((df.aulc <= 0.55).sum())} of {len(df)}; plateau ≥ 0.99: {int((df.plateau >= 0.99).sum())}.")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=64)
    ap.add_argument("--procs", type=int, default=10)
    ap.add_argument("--report-only", action="store_true")
    ap.add_argument("--results", default="results_registered", help="results dir; 'results' = the deviation run (DEVIATION.md)")
    a = ap.parse_args()
    global OUT
    global RES010
    if a.results == "results":
        OUT, RES010 = OUT / "deviation", "results"
    OUT.mkdir(parents=True, exist_ok=True)
    res = HERE / a.results
    if not a.report_only:
        jobs = [(SEED0 + s, smp, c) for s in range(a.seeds) for smp in SAMPLES for c in CONDS]
        t = time.time()
        with Pool(a.procs) as pool:
            rows = [r for rs in pool.imap_unordered(job, jobs, chunksize=2) for r in rs]
        res.mkdir(exist_ok=True)
        pd.DataFrame(rows).sort_values(["seed", "sample", "cond", "source", "variant"]).to_csv(res / "runs.csv", index=False)
        cal = {s: {k: (float(v) if k in ("g", "D") else int(v.sum())) for k, v in extra(s).items() if k != "f"} for s in SAMPLES}
        (res / "meta.json").write_text(json.dumps(dict(seeds=[SEED0, SEED0 + a.seeds - 1], task=task.P, calibration=cal,
                                                       wall_s=round(time.time() - t, 1)), indent=1))
    t = tables(pd.read_csv(res / "runs.csv"))
    (OUT / "tables.md").write_text(t + "\n")
    print(t)


if __name__ == "__main__":
    main()
