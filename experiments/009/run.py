"""Experiment 009: out-degree permutation within DoOR-input PNs. See PLAN.md.

    uv run python experiments/009/run.py [--seeds 30] [--procs 10] [--report-only]
"""
import argparse
import importlib.util
import json
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

from neuralpet import mb
from neuralpet.odors import door_odors

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "reports" / "009"
PK = ["random", "pn_out_perm", "pn_out_perm_live", "pn_out_perm_silent", "pn_out"]


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


r7 = _load("run007", ROOT / "experiments" / "007" / "run.py")
rep, r1 = r7.rep, r7.r6.r1

# "live" PN = non-zero DoOR value for >= 1 odorant (adapter v4); decided from the odour table only.
_d = np.load(ROOT / "data" / "mb" / "mb.npz")
LIVE = door_odors(_d["glom_names"], _d["glom_of_pn"])[0].sum(0) > 0
mb.WIRINGS["pn_out_perm_live"] = lambda W, r: mb.permute_rows(mb.keep_row_degree(W, r), r, np.flatnonzero(LIVE))
mb.WIRINGS["pn_out_perm_silent"] = lambda W, r: mb.permute_rows(mb.keep_row_degree(W, r), r, np.flatnonzero(~LIVE))


def job(args):
    return r7.job(args)


def f(t):
    return f"{t[0]:.3g} [{t[1]:.3g}, {t[2]:.3g}]"


def tables(df):
    L = ["# Experiment 009 tables (generated by experiments/009/run.py)\n",
         f"DoOR odours; PN→KC variants, KC→MBON real. Live PNs: {int(LIVE.sum())} of {len(LIVE)}. "
         "Cells: mean [95% bootstrap CI], 30 seeds, paired.\n"]
    mets = ["M2_ratio", "plateau_ratio", "M3_ratio", "M2_pooled"]
    for sp in df.sparsity.unique():
        d = df[df.sparsity == sp]
        L += [f"\n## sparsity = {sp}\n", "| metric | " + " | ".join(PK) + " |", "|---|" + "---|" * len(PK)]
        for m in mets:
            L.append(f"| {m} | " + " | ".join(f(rep.boot_ci(d[d.wiring == c][m])) for c in PK) + " |")
        p = d.pivot(index="seed", columns="wiring")
        L += ["", "| contrast | metric | mean diff [95% CI] | d_z |", "|---|---|---|---|"]
        for lab, a, b in [("Q1 pn_out − pn_out_perm_live", "pn_out", "pn_out_perm_live"),
                          ("Q2 pn_out − pn_out_perm_silent", "pn_out", "pn_out_perm_silent"),
                          ("Q3 pn_out − pn_out_perm", "pn_out", "pn_out_perm"),
                          ("ref pn_out_perm_live − random", "pn_out_perm_live", "random")]:
            for m in mets[:2]:
                diff = p[m][a] - p[m][b]
                sd = diff.std(ddof=1)
                L.append(f"| {lab} | {m} | {f(rep.boot_ci(diff))} | {diff.mean() / sd if sd > 0 else float('nan'):.2f} |")
    return "\n".join(L)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--seeds", type=int, default=30)
    a.add_argument("--procs", type=int, default=10)
    a.add_argument("--report-only", action="store_true")
    a = a.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    res = HERE / "results"
    if not a.report_only:
        W_pk, _, glom = r1.load()
        fr = {"sparse": 0.10, "literal": r1.literal_fraction(W_pk, glom)}
        jobs = [(s, "door", pk, sp, fr[sp]) for s in range(a.seeds) for pk in PK for sp in fr]
        t = time.time()
        with Pool(a.procs) as pool:
            rows = pool.map(job, jobs, chunksize=1)
        res.mkdir(exist_ok=True)
        pd.DataFrame(rows).to_csv(res / "runs.csv", index=False)
        (res / "meta.json").write_text(json.dumps(dict(seeds=a.seeds, fractions=fr, n_live=int(LIVE.sum()),
                                                       wall_s=round(time.time() - t, 1))))
    t = tables(pd.read_csv(res / "runs.csv"))
    (OUT / "tables.md").write_text(t + "\n")
    print(t)


if __name__ == "__main__":
    main()
