"""Experiment 002: state-modulated vs matched-constant reward dopamine in the pet. See PLAN.md.

    uv run python experiments/002/run.py [--seeds 30] [--steps 6000] [--procs 10]
"""
import argparse
import json
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

from neuralpet.pet import Pet

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT_REP = ROOT / "reports" / "002"


def load():
    d = np.load(ROOT / "data" / "mb" / "mb.npz")
    return d["W_pnkc"], d["W_kcmbon"], d["glom_of_pn"]


def simulate(seed, steps, da_const):
    p = Pet(*load(), seed=seed, da_const=da_const)
    energy = np.empty(steps)
    for i in range(steps):
        p.step()
        energy[i] = p.energy
    v = p.learned_valence()
    ev = [e for _, e in p.events]
    return dict(seed=seed, mean_energy=float(energy[1000:].mean()),
                frac_starving=float((energy[1000:] == 0).mean()),
                meals=ev.count("eat"), toxic=ev.count("toxic"),
                valence_gap=float(np.mean(v[:2]) - np.mean(v[2:])),
                mean_da_r=float(np.mean(p.da_rewards)) if p.da_rewards else None)


def run_pair(args):
    seed, steps = args
    on = simulate(seed, steps, None)
    c = on["mean_da_r"] if on["mean_da_r"] is not None else 0.5
    return [dict(on, cond="on", da_const=None), dict(simulate(seed, steps, c), cond="off", da_const=c)]


def boot(x, n=10000):
    x = np.asarray(x, float)
    m = np.random.default_rng(0).choice(x, (n, len(x))).mean(1)
    return x.mean(), *np.percentile(m, [2.5, 97.5])


def report(df):
    OUT_REP.mkdir(parents=True, exist_ok=True)
    p = df.pivot(index="seed", columns="cond")
    lines = ["# Experiment 002 tables (generated by experiments/002/run.py)\n",
             f"n = {df.seed.nunique()} seeds per condition. Cells: mean [95% bootstrap CI].\n",
             "| metric | on | off (matched) | on − off (paired) | d_z |", "|---|---|---|---|---|"]
    for m in ["mean_energy", "meals", "toxic", "valence_gap", "frac_starving"]:
        d = p[m]["on"] - p[m]["off"]
        dz = d.mean() / d.std(ddof=1) if d.std(ddof=1) > 0 else float("nan")
        f = lambda t: f"{t[0]:.3g} [{t[1]:.3g}, {t[2]:.3g}]"
        lines.append(f"| {m} | {f(boot(p[m]['on']))} | {f(boot(p[m]['off']))} | {f(boot(d))} | {dz:.2f} |")
    t = "\n".join(lines)
    (OUT_REP / "tables.md").write_text(t + "\n")
    print(t)


def main():
    a = argparse.ArgumentParser()
    a.add_argument("--seeds", type=int, default=30)
    a.add_argument("--steps", type=int, default=6000)
    a.add_argument("--procs", type=int, default=10)
    a = a.parse_args()
    t = time.time()
    with Pool(a.procs) as pool:
        rows = [r for pair in pool.map(run_pair, [(s, a.steps) for s in range(a.seeds)]) for r in pair]
    (HERE / "results").mkdir(exist_ok=True)
    df = pd.DataFrame(rows)
    df.to_csv(HERE / "results" / "runs.csv", index=False)
    (HERE / "results" / "meta.json").write_text(json.dumps(dict(seeds=a.seeds, steps=a.steps,
                                                                wall_s=round(time.time() - t, 1))))
    report(df)


if __name__ == "__main__":
    main()
